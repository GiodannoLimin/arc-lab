import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { requiredSpeed, G, type Shot } from "../src/science/physics";
import {
  DEFAULT_REBOUNDS as O,
  simulateRebounds,
  sampleRebounds,
  impact,
  kinetic,
  contactGeometry,
  freeFlight,
  type State,
} from "../src/science/rebounds";
const shot: Shot = {
  angle: 52,
  speed: requiredSpeed(6.75, 2, 52),
  height: 2,
  distance: 6.75,
  bearing: 0,
  aim: 0,
};
const states: State = {
  time: 0,
  p: { x: 0, y: 2, z: 0 },
  v: { x: 2, y: -3, z: 1 },
  w: { x: 1, y: 2, z: 3 },
  q: [0, 0, 0, 1],
};
const elastic = impact(
  states,
  { x: 0, y: 1, z: 0 },
  { restitution: 1, friction: 0 },
  { ...O, bounceThreshold: 0 },
);
const elasticEnergyError = Math.abs(kinetic(states) - kinetic(elastic));
assert.ok(elasticEnergyError < 1e-12);
const fixtures = [
  { ...shot },
  { ...shot, angle: 35, speed: 9.5 },
  { ...shot, angle: 35, speed: 9.6 },
  { ...shot, angle: 30, speed: 12 },
];
const expected = ["Clean swish", "Rim-assisted", "Backboard-assisted", "Miss"];
const rows = fixtures.map((s, i) => {
  const r = simulateRebounds(s, "FIBA");
  assert.equal(r.outcome, expected[i]);
  assert.ok(r.settled && !r.limited);
  let minimumClearance = Infinity;
  for (const segment of r.segments)
    for (const f of [0, 0.5, 1]) {
      const p = freeFlight(
        segment.start,
        (segment.end - segment.start.time) * f,
        segment.acceleration,
      ).p;
      for (const surface of ["floor", "rim", "backboard"] as const)
        minimumClearance = Math.min(
          minimumClearance,
          contactGeometry(p, "FIBA", surface).gap,
        );
    }
  assert.ok(minimumClearance > -3e-7);
  return {
    shot: s,
    outcome: r.outcome,
    scoreTime: r.scoreTime,
    contacts: r.contacts.length,
    floorBounces: r.contacts.filter((c) => c.surface === "floor").length,
    settled: r.settled,
    settledTime: r.final.time,
    finalKineticEnergy: kinetic(r.final),
    minimumSampledClearance: minimumClearance,
  };
});
const coarse = simulateRebounds(fixtures[3], "FIBA", {
    step: 1 / 120,
    maxTime: 2,
  }),
  fine = simulateRebounds(fixtures[3], "FIBA", { step: 1 / 480, maxTime: 2 });
const a = sampleRebounds(coarse, 1).p,
  b = sampleRebounds(fine, 1).p;
const contactTimeError = Math.abs(
    coarse.contacts[0].time - fine.contacts[0].time,
  ),
  positionError = Math.hypot(a.x - b.x, a.y - b.y, a.z - b.z);
assert.ok(contactTimeError < 1e-6 && positionError < 1e-4);
const baseline = JSON.parse(
  readFileSync("artifacts/phase3-seed-42.json", "utf8"),
);
assert.equal(baseline.baseline.hits, 817);
assert.equal(baseline.best.hits, 1615);
assert.equal(baseline.best.angle, 59);
const report = {
  status: "PASS",
  gravity: G,
  options: O,
  elasticEnergyError,
  stepRefinement: {
    coarse: 1 / 120,
    fine: 1 / 480,
    contactTimeAbsoluteError: contactTimeError,
    positionAbsoluteError: positionError,
  },
  rows,
  statistics: {
    definition:
      "Unchanged swish-only baseline; no rebound-inclusive optimization performed",
    baseline: baseline.baseline,
    best: baseline.best,
  },
};
writeFileSync(
  "artifacts/rebound-validation.json",
  JSON.stringify(report, null, 2),
);
writeFileSync(
  "COLLISION_VALIDATION.md",
  `# Executed rebound validation\n\nGenerated by \`pnpm validate:rebounds\`, which executes the rebound test suite before this report. Physics parameters are assumptions, not experimentally validated.\n\n- Elastic frictionless kinetic energy absolute error: ${elasticEnergyError} J (expected <1e-12 J): PASS.\n- Fixed-step refinement, 120 vs 480 Hz: first board impact time error ${contactTimeError} s (<1e-6 s), position difference at 1 s ${positionError} m (<1e-4 m): PASS. This is a selected smooth rebound case, not a uniform error bound for chaotic rim sequences.\n\n| Shot angle / speed | Result | Contacts / floor bounces | Settling time | Minimum sampled clearance | Final kinetic energy |\n|---|---|---:|---:|---:|---:|\n${rows.map((r) => `| ${r.shot.angle}° / ${r.shot.speed.toFixed(5)} m/s | ${r.outcome} | ${r.contacts} / ${r.floorBounces} | ${r.settledTime.toFixed(5)} s | ${r.minimumSampledClearance} m | ${r.finalKineticEnergy} J |`).join("\n")}\n\nAll four fixtures settled without a solver limit. Clearance checks sample each solver segment at its start, middle and end; CCD itself uses conservative advancement rather than these samples. There is no penetration at the tested sampling points beyond the stated 3e-7 m tolerance.\n\n## Probability and optimal parameters\n\nThe existing baseline was rerun with \`pnpm validate\` and retained exactly 817/10,000 swishes at the minimum-speed strategy (49.383605°, 8.787068 m/s), and 1,615/10,000 at the best-found strategy (59°, 9.091496 m/s), seed 42. Neither the scoring definition nor the optimizer was changed. No collision-inclusive probabilities or optimal parameters are claimed.\n\nSee [REBOUND_MODEL.md](REBOUND_MODEL.md) for restitution, friction, rotational inertia, settling approximations, scoring definitions, tolerances, numerical limits, and references.\n`,
);
