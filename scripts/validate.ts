import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { validateNumerically } from "../src/science/numerics";
import { experiment, type Config } from "../src/science/statistics";
import { requiredSpeed } from "../src/science/physics";
const validation = validateNumerically();
for (const r of validation.rows) {
  assert.ok(r.angleAbsoluteError < 1e-5);
  assert.ok(r.speedRelativeError < 1e-12);
  assert.ok(r.maxTargetError < 1e-9);
}
writeFileSync(
  "artifacts/phase2-validation.json",
  JSON.stringify(validation, null, 2),
);
const metrics = [
  "angleAbsoluteError",
  "angleRelativeError",
  "speedAbsoluteError",
  "speedRelativeError",
  "maxPositionError",
  "maxRelativePositionError",
  "maxTargetError",
] as const;
const max = Object.fromEntries(
  metrics.map((k) => [k, Math.max(...validation.rows.map((r) => r[k]))]),
);
// This experiment is deliberately executed only after the Phase 2 assertions.
const config: Config = {
  shot: {
    angle: 52,
    speed: requiredSpeed(6.75, 2, 52),
    height: 2,
    distance: 6.75,
    bearing: 0,
    aim: 0,
  },
  league: "FIBA",
  samples: 10000,
  seed: 42,
  errors: { angle: 1.5, speed: 0.12, aim: 0.6, correlation: 0 },
};
const result = experiment(config);
writeFileSync("artifacts/phase3-seed-42.json", JSON.stringify(result, null, 2));
const pct = (x: number) => (x * 100).toFixed(2) + "%";
const table = [result.baseline, result.best]
  .map(
    (x, i) =>
      `| ${i ? "Statistical best found" : "Analytical minimum speed"} | ${x.angle.toFixed(6)}° | ${x.speed.toFixed(6)} m/s | ${pct(x.p)} | ${pct(x.lo)}–${pct(x.hi)} |`,
  )
  .join("\n");
const report = `# Executed validation report

Generated by \`pnpm validate\`. Re-run this command to regenerate actual results. Phase 2 tests/assertions run before the statistical experiment.

## Audit and fixes

The 13 pre-existing tests passed on inspection. Audit nevertheless found: gravity 9.80665 instead of the requested 9.81; rendered trajectories continued through contact despite the scoring classifier rejecting it; frame deltas above 50 ms were capped, causing slow playback below 20 fps. These are corrected. Invalid integration steps and nonfinite shots now fail safely.

## Phase 2 gate: PASS

Internal coordinates use y for height; the requested z-height equations are equivalent after renaming axes. Gravity is exactly 9.81 m/s². Tests verify descending finite-sphere scoring, missed shallow and off-axis shots, continuous rim and board contact stops, floor contact, 10/30/60/144 fps playback including stalls, NBA/FIBA geometry consistency, and seeded statistical prerequisites.

48 distance/height/league cases cover distances 3, 4, 5, 6, 6.75, 7.239, 8, 9 m; release heights 1.5, 2, 2.5 m; both rim heights. At each case 5 angles (35–75°) and 3 integration steps (0.1, 0.01, 0.001 s) yield 720 RK4 target checks. Target checks verify reaching a point, not whether it is reached descending or whether a sphere scores.

| Executed comparison | Expected tolerance | Actual maximum error | Status |
|---|---:|---:|---|
| Golden-section vs analytical optimum angle | <1e-5° | ${max.angleAbsoluteError}° (relative ${max.angleRelativeError}) | PASS |
| Numerical optimum speed vs analytical | relative <1e-12 | ${max.speedAbsoluteError} m/s (relative ${max.speedRelativeError}) | PASS |
| Independent RK4 vs analytical position | <1e-9 m | ${max.maxPositionError} m (relative ${max.maxRelativePositionError}) | PASS |
| RK4 position vs target | <1e-9 m | ${max.maxTargetError} m | PASS |

Golden-section search does not use the differentiated optimum; it minimizes the point-target speed function. RK4 independently validates trajectory and target speed. Extremely small speed errors alongside larger angle errors reflect the flat objective near its minimum and floating-point precision. Relative position errors use the target position's Euclidean norm (with a 1 m lower bound).

## Phase 3: executed seed-42 experiment

FIBA, distance 6.75 m, ball center release height 2 m. Illustrative normal SDs: angle 1.5°, speed 0.12 m/s, direction 0.6°, angle–speed correlation 0. Each candidate has 10,000 trials; ${result.searchCandidates} search evaluations plus independent validation and sensitivity produce ${result.shots.toLocaleString()} scoring evaluations. Estimates below use the fresh validation stream, not selection estimates.

| Strategy | Intended angle | Intended speed | Estimated clean scoring | 95% Wilson CI |
|---|---:|---:|---:|---:|
${table}

Best-found intended direction: ${result.best.aim.toFixed(3)}°. Paired difference: ${(result.difference.value * 100).toFixed(2)} percentage points, approximate 95% interval ${(result.difference.lo * 100).toFixed(2)} to ${(result.difference.hi * 100).toFixed(2)} pp. ${result.difference.lo > 0 ? "This configured experiment resolves an improvement on independent validation." : "This experiment does not establish an improvement."} Zero-error tests separately verify that the analytical and statistical solutions can coincide.

## Remaining limitations

- This report's probabilities use the clean-shot baseline only. Baseline reference paths end at first contact. The separate interactive rebound solver and default physical subset replay include rim/board baskets, but do not alter these probabilities; see COLLISION_VALIDATION.md.
- Gravity-only spherical projectile; no drag, spin, deformation, net forces, release-height variation, or player calibration. Rendered supports and net are not collision surfaces.
- Continuous certification conservatively rejects unresolved grazing at depth 20 or interval <1e-7 s. Representative contact time bisects the certified safe prefix to 1e-8 s; grazing may stop conservatively early.
- Statistical search is bounded, with coarse grid and local refinement; “best found” is not a proven global probability optimum.
- Gaussian errors are assumptions. Wilson intervals quantify sampling noise conditional on this model, not accuracy for real players. Paired difference normal intervals can be unreliable with rare discordant outcomes. Exploratory chart intervals are not selection-adjusted.
- Displayed success/miss paths are deliberately balanced representatives, never a sample from which to read frequencies. Court lines are visual nominal references; no player-foot eligibility model exists.

## Manual checks

1. Run \`pnpm dev\` and open its printed localhost URL.
2. Set 52° at 6.75 m and 2 m release; use Aim trajectory, launch, and inspect Side and Overhead views. A centered descending shot should clear the rim.
3. Set 25° and use Aim trajectory; a centered point trajectory can fail sphere clearance. In interactive mode the ball rebounds at contact. Try the Rim-assisted and Backboard-assisted presets; verify continued bounces and floor settling. Original baseline replay still ends at contact.
4. Open Errors, select a court position in Shot → Position, configure error SDs/trials/seed, and calculate probabilities. Inspect Results for the curve, validation intervals, fixed-strategy sensitivity and blue/orange baseline reference paths.
5. Export JSON, rerun the same seed/settings, and compare hits and intervals (elapsed runtime may vary). Change a setting and confirm saved results are marked stale.
6. Set every error SD to zero and rerun; the selected strategy should retain the minimum-speed baseline if it is a clean shot. Try 9:16 and phone layouts.

Automated numerical suites: \`pnpm test\`. Reproduce this report: \`pnpm validate\`. Type check and static production build: \`pnpm build\`.
`;
writeFileSync("VALIDATION_REPORT.md", report);
